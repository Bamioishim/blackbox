// Hashes the deterministic offer and settlement security rules so receipts can publish them.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const files = ["src/lib/schema.ts", "src/lib/referee.ts", "src/lib/referee-security.ts"];
const h = createHash("sha256");
for (const f of files) {
  const src = readFileSync(f, "utf8").replace(/\r\n/g, "\n");
  h.update(f + "\n" + src + "\n");
}
const hash = h.digest("hex");
writeFileSync(
  "src/lib/referee-hash.generated.ts",
  `// Generated by scripts/referee-hash.mjs. Do not edit.\nexport const REFEREE_HASH = "${hash}";\nexport const LEGACY_REFEREE_HASHES = ["5c194b8f6fdd8688f375d5111036fe3993b636b1ebb4c83efc5e627c649b6673"];\nexport const REFEREE_FILES = ${JSON.stringify(files)};\n`,
);
console.log("referee hash", hash);
