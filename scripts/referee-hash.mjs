// Hashes the referee source (referee.ts + schema.ts) so the UI and README can publish it.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const files = ["src/lib/schema.ts", "src/lib/referee.ts"];
const h = createHash("sha256");
for (const f of files) {
  const src = readFileSync(f, "utf8").replace(/\r\n/g, "\n");
  h.update(f + "\n" + src + "\n");
}
const hash = h.digest("hex");
writeFileSync(
  "src/lib/referee-hash.generated.ts",
  `// Generated by scripts/referee-hash.mjs. Do not edit.\nexport const REFEREE_HASH = "${hash}";\nexport const REFEREE_FILES = ${JSON.stringify(files)};\n`,
);
console.log("referee hash", hash);
